// Reports joined with the species they refer to, newest first
export function getReports(locale) {
    return REPORTS
        .map((report) => {
            const species = getSpeciesBySlug(report.speciesSlug, locale)
            return {
                ...report,
                species: species && {
                    slug: species.slug,
                    commonName: species.commonName,
                    scientificName: species.scientificName,
                    category: species.category,
                    thumbnail: species.thumbnail,
                },
            }
        })
        .filter(({ species }) => species)
        .sort((a, b) => b.date.localeCompare(a.date))
}
